def get_scenario(name):
    """
    Return (load_kw_96, pv_kw_96, ev_bool_96) arrays for a named scenario.

    Parameters
    ----------
    name : str  key from SCENARIOS dict

    Returns
    -------
    tuple (load_array, pv_array, ev_array, label)
    """
    if name not in SCENARIOS:
        raise ValueError(f"Unknown scenario '{name}'. Choose from: {list(SCENARIOS)}")
    sc = SCENARIOS[name]
    load = get_faculty_load_profile(sc["load"])
    pv   = get_pv_profile(sc["solar"])
    ev   = get_ev_profile(sc["ev"])
    return load, pv, ev, sc["label"]


