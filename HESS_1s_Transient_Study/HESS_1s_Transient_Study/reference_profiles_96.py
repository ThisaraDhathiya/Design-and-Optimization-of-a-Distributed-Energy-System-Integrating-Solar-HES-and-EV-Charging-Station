# ── EV DEMAND SCHEDULE ────────────────────────────────────────────────────────
def ev_schedule_default():
    """
    Default EV arrival pattern.
    EV arrives 08:00 (step 32), departs 14:00 (step 56).
    Returns 96-element bool array (True = EV plugged in this step).
    """
    schedule = np.zeros(STEPS, dtype=bool)
    schedule[32:57] = True   # 08:00 to 14:15
    return schedule

def ev_schedule_morning():
    """EV charges 07:00 – 11:00."""
    s = np.zeros(STEPS, dtype=bool)
    s[28:44] = True
    return s

def ev_schedule_split():
    """Two separate EV sessions: 08:00-11:00 and 13:00-16:00."""
    s = np.zeros(STEPS, dtype=bool)
    s[32:44] = True   # morning session
    s[52:64] = True   # afternoon session
    return s

def ev_schedule_none():
    """No EV charging — battery and PV study only."""
    return np.zeros(STEPS, dtype=bool)


# ── MAIN PROFILE BUILDERS ─────────────────────────────────────────────────────
def get_faculty_load_profile(day_type="working"):
    """
    Return 96-element array of actual faculty load in kW.

    Parameters
    ----------
    day_type : str  'working' | 'holiday'
    """
    if day_type == "holiday":
        return _HOLIDAY_PU * PEAK_HOL_KW
    return _WORKING_DAY_PU * PEAK_WD_KW

def get_pv_profile(scenario="clear"):
    """
    Return 96-element array of total PV generation in kW.

    Parameters
    ----------
    scenario : str  'clear' | 'cloudy' | 'none'
    """
    if scenario == "cloudy":
        return _CLOUDY_DAY_PU * TOTAL_PV_KWP
    if scenario == "none":
        return _NO_SOLAR_PU.copy()
    return _CLEAR_DAY_PU * TOTAL_PV_KWP

def get_ev_profile(session_type="default"):
    """
    Return 96-element bool array indicating when EV is connected.

    Parameters
    ----------
    session_type : str  'default' | 'morning' | 'split' | 'none'
    """
    if session_type == "morning":
        return ev_schedule_morning()
    if session_type == "split":
        return ev_schedule_split()
    if session_type == "none":
        return ev_schedule_none()
    return ev_schedule_default()


